"""
FastAPI application for AstroGuard-X.

Run:   uvicorn backend.main:app --host 0.0.0.0 --port 8000
Docs:  http://localhost:8000/docs  (OpenAPI generated by FastAPI)

Open-source attribution: FastAPI (MIT) + Starlette (BSD-3), Uvicorn (BSD-3),
python-multipart (Apache-2.0) for ECG file uploads.
"""
from __future__ import annotations

import logging
from contextlib import asynccontextmanager
from typing import Any, Dict, List, Optional

from fastapi import FastAPI, File, HTTPException, Query, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

from backend.gamification import BADGES
from backend.schemas import Assessment, CompletionResult, GamificationState, ReadingIn, TaskOut
from backend.service import AstroGuardService, get_service
from utils.config import get_settings
from utils.reference_ranges import CATEGORIES, LEVELS, PARAMETERS

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")

MAX_ECG_UPLOAD_BYTES = 50 * 1024 * 1024


@asynccontextmanager
async def lifespan(app: FastAPI):
    app.state.service = get_service()  # loads (or trains) the model once at start-up
    yield
    app.state.service.ecg.stop_service()


app = FastAPI(title="AstroGuard-X API", version="1.0.0", lifespan=lifespan,
              description="AI-powered astronaut health monitoring with gamified mitigation tasks. "
                          "Research / demonstration software - not a medical device.")
app.add_middleware(CORSMiddleware, allow_origins=get_settings().cors_origins, allow_methods=["*"], allow_headers=["*"])


def svc() -> AstroGuardService:
    return app.state.service


class ChatIn(BaseModel):
    question: str


# ----------------------------------------------------------------------- meta
@app.get("/health", tags=["meta"])
def health() -> Dict[str, Any]:
    s = svc()
    return {"status": "ok", "model": s.model_info(), "gemini": s.advisor.status(), "ecg": s.ecg_status()}


@app.get("/parameters", tags=["meta"])
def parameters() -> Dict[str, Any]:
    """Parameter registry: units, normal ranges and categories (drives UI forms)."""
    return {
        "levels": [{"key": k, "label": l, "color": c, "meaning": m} for k, l, c, m in LEVELS],
        "categories": CATEGORIES,
        "parameters": [{"key": p.key, "name": p.name_en, "name_tr": p.name_tr, "unit": p.unit, "category": p.category,
                        "kind": p.kind, "ideal": p.ideal, "normal": p.normal, "warn": p.warn, "danger": p.danger,
                        "bounds": p.bounds, "decimals": p.decimals, "notes": p.notes} for p in PARAMETERS],
    }


# ------------------------------------------------------------------ assessment
@app.post("/astronauts/{astronaut_id}/assess", response_model=Assessment, tags=["assessment"])
def assess(astronaut_id: str, reading: ReadingIn, lang: str = Query("en", pattern="^(en|tr)$")) -> Assessment:
    try:
        return svc().assess(astronaut_id, reading, lang)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))


@app.get("/astronauts/{astronaut_id}/latest", tags=["assessment"])
def latest(astronaut_id: str) -> Optional[Dict[str, Any]]:
    return svc().latest(astronaut_id)


@app.get("/astronauts/{astronaut_id}/history", tags=["assessment"])
def history(astronaut_id: str, n: int = Query(60, ge=1, le=500)) -> List[Dict[str, Any]]:
    return svc().risk_history(astronaut_id, n)


@app.post("/astronauts/{astronaut_id}/chat", tags=["assessment"])
def chat(astronaut_id: str, body: ChatIn, lang: str = Query("en", pattern="^(en|tr)$")) -> Dict[str, str]:
    return svc().chat(astronaut_id, body.question, lang)


# ------------------------------------------------------------- tasks & rewards
@app.get("/astronauts/{astronaut_id}/tasks", response_model=List[TaskOut], tags=["tasks"])
def tasks(astronaut_id: str, status: Optional[str] = Query(None, pattern="^(pending|done)$")) -> List[TaskOut]:
    return svc().list_tasks(astronaut_id, status)


@app.post("/astronauts/{astronaut_id}/tasks/{task_id}/complete", response_model=CompletionResult, tags=["tasks"])
def complete_task(astronaut_id: str, task_id: int) -> CompletionResult:
    try:
        return svc().complete_task(astronaut_id, task_id)
    except KeyError as exc:
        raise HTTPException(status_code=404, detail=str(exc))


@app.get("/astronauts/{astronaut_id}/gamification", response_model=GamificationState, tags=["tasks"])
def gamification(astronaut_id: str) -> GamificationState:
    return svc().gamification_state(astronaut_id)


@app.get("/badges", tags=["tasks"])
def badges() -> List[Dict[str, str]]:
    return [{"id": b.id, "name": b.name, "description": b.description, "icon": b.icon} for b in BADGES]


# ------------------------------------------------------------------------- ECG
@app.get("/ecg/status", tags=["ecg"])
def ecg_status() -> Dict[str, Any]:
    return svc().ecg_status()


@app.post("/ecg/analyze", tags=["ecg"])
def ecg_analyze(file: UploadFile = File(...)) -> Dict[str, Any]:
    # Plain `def`: FastAPI runs it in a worker thread, so a slow ECG model never blocks the event loop.
    content = file.file.read(MAX_ECG_UPLOAD_BYTES + 1)
    if len(content) > MAX_ECG_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="ECG file too large (max 50 MB)")
    try:
        return svc().analyze_ecg(content, file.filename or "ecg.npy")
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))


@app.get("/ecg/sample/{class_code}", tags=["ecg"])
def ecg_sample(class_code: str) -> Dict[str, Any]:
    return svc().ecg_sample(class_code)
